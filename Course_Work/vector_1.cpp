#include <iostream>
#include <memory>
#include <algorithm>
#include <stdexcept>

class vector // Создание класса с  названием 'vector'
{
    // Задаём переменные для вектора
    int sz;       // Размер вектора (количество элементов в нём)
    double *elem; // Указатель на первый элемент массива типа 'double' (элементы в памяти храняться последовательно)

public:
    vector(int s)
        : sz{s}, elem{new double[s]} // Констуктор создания | создаёт 'пустой' вектор с размером вектора, равному введённому пользователем занчению 's', предварительно резервируя 's' ячеек памяти
    {
        // Цикл для заполнения элемментов вектора 'пустыми значениями', нулями
        for (int i = 0; i < s; ++i)
            elem[i] = 0;
    }

    ~vector() { delete[] elem; } // Деструктор (конструктор разрушения) | освобождает динамическую память, кучу(heap), от вектора

    int size() const { return sz; }             // Функция, позволяющая узнать размер (количество элементов) вектора
    double get(int n) const { return elem[n]; } // Функция, позволяющая получить элемент вектора с индексом 'n'
    void set(int n, double v) { elem[n] = v; }  // Функция, позволяющая задать элементу вектора с индексом 'n' значение 'v'
};

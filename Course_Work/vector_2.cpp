#pragma once
#include "vector_2.h"

/* Констуктор создания */
vector::vector(int s) : sz{s}, elem{new double[s]} // Констуктор создания | создаёт 'пустой' вектор с размером вектора, равному введённому пользователем занчению 's', предварительно резервируя 's' ячеек памяти
{                                                  // Цикл для заполнения элемментов вектора 'пустыми значениями', нулями
    for (int i = 0; i < s; ++i)
    {
        elem[i] = 0;
    }
}

/* Деструктор (конструктор разрушения) */
vector::~vector() { delete[] elem; } // Особождает динмическую память (кучу/heap) от вектора

/* Констуктор копирования */
vector::vector(const vector &a) : sz{a.sz}, elem{new double[a.sz]} // Выделение нового блока памяти под копию
{
    for (int i = 0; i < a.sz; ++i)
    {
        elem[i] = a.elem[i];
    } // Поэлементное копирование значений в новый вектор
}

/* Оператор присваивания копированием */
vector &vector::operator=(const vector &a)
{
    if (this == &a)
    {
        return *this;
    } // Проверка на самоприсваивание

    double *p = new double[a.sz]; // Выделение памяти под копию данных
    // for (int i = 0; i < a.sz; i++)
    // {
    //     p[i] = a.elem[i];
    // } // Копирование значений из старого вектора в копию
    std::copy(a.elem, a.elem + a.sz, elem); // Вариант Б.Страуструпа
    delete[] elem; // Удаление старых значений
    elem = p;      // Меняем указатель | Указывал на старые данные, будет на новые
    sz = a.sz;     // Тот же размер вектора
    return *this;
};
// Получаем вектор с такими же значениями, но находящимися под другим указателем

/* Конструктор перемещения */
vector::vector(vector &&a) : sz{a.sz}, elem{a.elem}
{
    a.sz = 0;
    a.elem = nullptr;
} // Обнуление старого вектора

/* Оператор присваивания перемещением */
vector &vector::operator=(vector &&a)
{
    if (this == &a)
        return *this;

    delete[] elem;    // Удаляем старые данные вектора
    elem = a.elem;    // Переносим данные из старого вектора в новый с помощью перенапраления указателя
    sz = a.sz;        // Делаем новому вектору такой же размер
    a.elem = nullptr; // Обнуляем старый указатель
    a.sz = 0;         // Обнуляем старый размер
    return *this;
}
// Старый вектор опустошён, а новый имеет его данные

/* Функции */

int vector::size() const { return sz; } // Функция, позволяющая узнать размер (количество элементов) вектора